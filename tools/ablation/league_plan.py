"""032-R20 ③: writes config/plans/arch-abl-pt-league.toml, the league of the architecture
comparison. Every pair of the seven models (ckpt-10000 of each run) plays 100 games: per map
2 x 25 games, the slots swapped after 25 (as the core-ablation head-to-head). The LSTM-GTrXL pair
is left out: its games are the second core ablation's head-to-head (core-ablation-pt-h2h.toml).

    python tools/ablation/league_plan.py            # rewrites the plan file
"""

import itertools
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "config" / "plans" / "arch-abl-pt-league.toml"
# Order fixes the matchup numbering (and so the game seeds): baseline, LSTM, variants.
MODELS = [
    "core-abl-gtrxl-pt",
    "core-abl-lstm-pt",
    "arch-abl-terrain-pt",
    "arch-abl-ctx-pt",
    "arch-abl-pool-pt",
    "arch-abl-outer-pt",
    "arch-abl-all-pt",
]
REUSED = {("core-abl-gtrxl-pt", "core-abl-lstm-pt")}
MAPS = ("fighting_spirit", "circuit_breaker")
GAMES = 25  # per map and slot order
# Above every other plan's games (core-ablation-pt-t0: 32800 + 600) and below 40000.
SEED_BASE = 35000


def pairs():
    return [p for p in itertools.combinations(MODELS, 2) if p not in REUSED]


def player(run: str) -> str:
    return f'{{ kind = "model", checkpoint = "checkpoints/{run}/ckpt-10000", sample = "stochastic" }}'


def render() -> str:
    lines = [
        "# 032-R20 (3) (user decision 2026-10-25): league of the architecture comparison, generated by",
        "# tools/ablation/league_plan.py (do not edit by hand). Seven models (ckpt-10000, relative to",
        "# URANIUM_SHARED_DIR), every pair 100 games: per map 25 + 25 with the slots swapped, stochastic",
        "# sampling, no z, replays kept. The LSTM-GTrXL pair comes from core-ablation-pt-h2h.toml.",
        f"# {len(pairs())} pairs x 4 matchups; matchup k is pair k // 4 in the script's pair order.",
        'name = "arch-abl-pt-league"',
        f"seed_base = {SEED_BASE}",
        "save_replay = true",
        "# As the core-ablation plans: up to about an hour of wall time per game when inference is slow.",
        "wall_timeout_s = 7200",
        "# 030-R10 / E-5: BC checkpoints get last_failed = 0 (BC data never has a failed command).",
        "zero_last_failed = true",
    ]
    for a, b in pairs():
        for m in MAPS:
            for p0, p1 in ((a, b), (b, a)):
                lines += ["[[matchup]]", f'map = "{m}"', f"games = {GAMES}", f"p0 = {player(p0)}", f"p1 = {player(p1)}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_bytes(render().replace("\n", "\r\n").encode("utf-8"))
    print(f"{OUT.relative_to(ROOT)}: {len(pairs())} pairs, {len(pairs()) * 4 * GAMES} games")
