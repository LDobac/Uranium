use std::fmt::Write as _;
use std::path::Path;

use anyhow::Result;

use crate::util::{Row, Status};

pub fn write(path: &Path, backend: &str, quick: bool, rows: &[Row]) -> Result<()> {
    let mut md = String::new();
    writeln!(md, "# BC250 Burn benchmark — backend `{backend}`{}\n", if quick { " (quick)" } else { "" })?;
    writeln!(md, "Generated by `cargo run -p bench --release -- --backend {backend}` (spec 060-R2).")?;
    writeln!(md, "Times are medians. Errors are vs. Flex (CPU) f32 with identical inputs and weights.\n")?;
    writeln!(md, "| case | shape | fwd ms | fwd+bwd ms | GFLOP/s | max abs err | max rel err | status |")?;
    writeln!(md, "|---|---|---|---|---|---|---|---|")?;
    let f = |v: Option<f64>, p: usize| v.map(|x| format!("{x:.p$}")).unwrap_or_else(|| "–".into());
    let e = |v: Option<f64>| v.map(|x| format!("{x:.1e}")).unwrap_or_else(|| "–".into());
    for r in rows {
        let status = match &r.status {
            Status::Ok => "ok".to_string(),
            Status::Inaccurate => format!("**inaccurate** ({})", r.note),
            Status::Failed(m) => format!("**failed**: `{}`", m.replace('|', "/").replace('`', "'")),
        };
        writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            r.name,
            r.shape,
            f(r.fwd_ms, 3),
            f(r.fwd_bwd_ms, 3),
            f(r.gflops, 0),
            e(r.max_abs_err),
            e(r.max_rel_err),
            status
        )?;
    }
    let failed: Vec<_> = rows.iter().filter(|r| matches!(r.status, Status::Failed(_))).map(|r| r.name.as_str()).collect();
    let inaccurate: Vec<_> = rows.iter().filter(|r| r.status == Status::Inaccurate).map(|r| r.name.as_str()).collect();
    writeln!(md, "\n## Summary\n")?;
    writeln!(md, "- failed / unsupported: {}", if failed.is_empty() { "none".into() } else { failed.join(", ") })?;
    writeln!(md, "- inaccurate: {}", if inaccurate.is_empty() { "none".into() } else { inaccurate.join(", ") })?;
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(path, md)?;
    Ok(())
}
