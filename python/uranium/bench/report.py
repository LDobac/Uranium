"""Bench reports (060-AC1, AC4, AC5): the generated markdown table in the Burn bench layout (case,
shape, times, GFLOP/s, error vs CPU, status) plus p95 and peak memory, and the raw JSON."""

import platform

import torch


def fmt(x, spec: str = ".3f") -> str:
    return "–" if x is None else format(x, spec)


def environment(backend: str, precision: str, device: torch.device) -> dict:
    env = {"backend": backend, "precision": precision, "torch": torch.__version__, "python": platform.python_version(), "os": platform.system()}
    if device.type == "cuda":
        p = torch.cuda.get_device_properties(device)
        env |= {"gpu_memory_gib": round(p.total_memory / 2**30, 1), "hip": torch.version.hip, "cuda": torch.version.cuda}
        env |= {"matmul_tf32": torch.backends.cuda.matmul.allow_tf32, "cudnn_tf32": torch.backends.cudnn.allow_tf32, "cudnn_benchmark": torch.backends.cudnn.benchmark}
    return env


def markdown(rows: list, env: dict, command: str) -> str:
    out = [f"Generated by `{command}` (spec 060-R2).", ""]
    out.append("Environment: " + ", ".join(f"{k} {v}" for k, v in env.items()) + ".")
    out.append("Times are medians over repetitions grown until the standard error is under 1% of the mean (warm-up excluded); p95 in brackets. Errors are vs. CPU f32 with identical inputs and weights.")
    out += ["", "| case | shape | fwd ms (p95) | fwd+bwd ms (p95) | GFLOP/s | max abs err | max rel err | peak GiB | status |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        t = lambda x: "–" if x is None else f"{x.median_ms:.3f} ({x.p95_ms:.3f})"  # noqa: E731
        status = r.status if not r.note else f"{r.status} ({r.note})"
        if r.status != "ok":
            status = f"**{r.status}**: `{r.note}`"
        out.append(f"| {r.case} | {r.shape} | {t(r.fwd)} | {t(r.fwd_bwd)} | {fmt(r.gflops, '.0f')} | {fmt(r.max_abs, '.1e')} | {fmt(r.max_rel, '.1e')} | {fmt(r.peak_gib, '.2f')} | {status} |")
    failed = [r.case for r in rows if r.status != "ok"]
    out += ["", f"- failed: {', '.join(failed) if failed else 'none'}"]
    return "\n".join(out) + "\n"


def bc_markdown(groups: list[dict], env: dict, command: str) -> str:
    out = [f"Generated by `{command}` (spec 060-R2, real-data BC updates).", "", "Environment: " + ", ".join(f"{k} {v}" for k, v in env.items()) + ".", ""]
    out += ["| lane group | updates | median s (p95) | mean s | data wait median s | peak GPU GiB | peak RSS GiB | last loss |", "|---|---|---|---|---|---|---|---|"]
    for g in groups:
        last = g["updates"][-1]["loss"]["total"] if g["updates"] else None
        out.append(f"| {g['group']} | {max(len(g['updates']) - 1, 0)} | {fmt(g['median_s'], '.2f')} ({fmt(g['p95_s'], '.2f')}) | {fmt(g['mean_s'], '.2f')} | {fmt(g['wait_median_s'], '.2f')} | {fmt(g['peak_gib'], '.2f')} | {fmt(g['peak_rss_gib'], '.2f')} | {fmt(last, '.5f')} |")
    for g in groups:
        if g.get("ops"):
            out += ["", f"Operators by device time, lane group {g['group']} (one update):", "", "| op | calls | self ms | cpu ms |", "|---|---|---|---|"]
            out += [f"| `{o['name']}` | {o['calls']} | {o['self_ms']} | {o['cpu_ms']} |" for o in g["ops"]]
    return "\n".join(out) + "\n"
